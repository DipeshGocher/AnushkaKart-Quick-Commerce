/**
 * Converts inline SVG string into a usable Data URI image src string
 */
export const getBrandSvgDataUri = (svgString) => {
  if (!svgString) return "";
  const encoded = encodeURIComponent(svgString)
    .replace(/'/g, "%27")
    .replace(/"/g, "%22");
  return `data:image/svg+xml;charset=utf-8,${encoded}`;
};

/**
 * Helper to get brand logo data URI or URL by brand name / slug / id
 */
export const getMobileBrandLogo = (brandName) => {
  if (!brandName) return null;
  const target = String(brandName).toLowerCase().trim();
  const found = MOBILE_BRAND_LOGOS.find(
    (b) =>
      b.id === target ||
      b.slug === target ||
      b.name.toLowerCase() === target ||
      target.includes(b.slug)
  );
  if (!found) return null;
  return {
    ...found,
    dataUri: found.imageAsset || getBrandSvgDataUri(found.svg)
  };
};

